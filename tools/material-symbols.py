#!/usr/bin/env python3
"""
Generates the app's icons from Material Symbols Rounded (Apache 2.0, Google) as Kotlin
ImageVectors (V7.3). Run from the repo root:

    python tools/material-symbols.py <cache-dir>

It downloads each SVG once into <cache-dir> (from fonts.gstatic.com) and writes:
  app/src/main/java/com/droidbubble/app/icons/IslandGlyphs.kt   island glyphs, weight 500, grade -25,
                                                               filled; optical size 24 (cards) and 20
                                                               (pill, bubble, alert pills: `Small`)
  app/src/main/java/com/droidbubble/app/icons/AppIcons.kt       settings app icons, weight 400, grade 0,
                                                               filled, optical size 24

Each SVG is a single path in a 960-unit box whose top is at y = -960; SymbolVector.kt shifts it down.
To add an icon: add a line to ISLAND or APP below and run the script again.
"""
import os
import re
import sys
import urllib.request

BASE = "https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded"

# Kotlin name -> Material Symbols name. The island catalogue (island/IslandIcons.kt) maps meanings
# onto these.
ISLAND = {
    "Alarm": "alarm", "Bluetooth": "bluetooth", "Call": "call", "CallEnd": "call_end", "Check": "check",
    "Close": "close", "Download": "download", "FlashlightOn": "flashlight_on", "LocalShipping": "local_shipping",
    "LockOpen": "lock_open", "Mic": "mic", "MusicNote": "music_note", "Notifications": "notifications",
    "NotificationsOff": "notifications_off", "Pause": "pause", "PlayArrow": "play_arrow", "Repeat": "repeat",
    "RepeatOne": "repeat_one", "Send": "send", "Shuffle": "shuffle", "SkipNext": "skip_next",
    "SkipPrevious": "skip_previous", "SportsSoccer": "sports_soccer", "Timer": "timer", "Vibration": "vibration",
    "Wifi": "wifi",
}
ISLAND_MIRRORED = {"Send"}

APP = {
    "Accessibility": "accessibility", "Animation": "animation", "Apps": "apps", "ArrowBack": "arrow_back",
    "ArrowForwardIos": "arrow_forward_ios", "AttachFile": "attach_file", "Bluetooth": "bluetooth",
    "BlurOn": "blur_on", "Bolt": "bolt", "BugReport": "bug_report", "Call": "call", "CheckCircle": "check_circle",
    "Close": "close", "Contrast": "contrast", "CropSquare": "crop_square", "Download": "download",
    "Feedback": "feedback", "FitScreen": "fit_screen", "FlashlightOn": "flashlight_on",
    "KeyboardArrowRight": "keyboard_arrow_right", "Lightbulb": "lightbulb", "Lock": "lock", "Menu": "menu",
    "MusicNote": "music_note", "Notifications": "notifications", "NotificationsActive": "notifications_active",
    "Palette": "palette", "PowerSettingsNew": "power_settings_new", "RecordVoiceOver": "record_voice_over",
    "Refresh": "refresh", "RoundedCorner": "rounded_corner", "Science": "science",
    "ScreenRotation": "screen_rotation", "Security": "security", "Send": "send", "Star": "star",
    "Straighten": "straighten", "Swipe": "swipe", "SystemUpdate": "system_update", "Timer": "timer",
    "Vibration": "vibration", "Videocam": "videocam", "Warning": "warning", "Wifi": "wifi",
}
APP_MIRRORED = {"ArrowBack", "ArrowForwardIos", "KeyboardArrowRight", "Send"}

ISLAND_STYLE = "wght500gradN25fill1"
APP_STYLE = "fill1"
OUT = "app/src/main/java/com/droidbubble/app/icons"


def fetch(cache, symbol, style, px):
    path = os.path.join(cache, f"{symbol}__{style}__{px}.svg")
    if not os.path.exists(path):
        url = f"{BASE}/{symbol}/{style}/{px}px.svg"
        with urllib.request.urlopen(url, timeout=20) as r:
            data = r.read()
        with open(path, "wb") as f:
            f.write(data)
    svg = open(path, encoding="utf-8").read()
    assert 'viewBox="0 -960 960 960"' in svg, (symbol, "unexpected viewBox")
    paths = re.findall(r'<path d="([^"]+)"', svg)
    assert len(paths) == 1, (symbol, f"{len(paths)} paths")
    assert re.fullmatch(r"[0-9A-Za-z.\-\s,]+", paths[0]), (symbol, "unexpected characters in path")
    return paths[0]


HEADER = """// Generated by tools/material-symbols.py from Material Symbols Rounded (Apache License 2.0,
// Copyright Google LLC). Do not edit by hand: change the script and run it again.
package com.droidbubble.app.icons

import androidx.compose.ui.graphics.vector.ImageVector
"""


def entry(kname, vname, d, px, mirrored, indent="    "):
    mirror = ", autoMirror = true" if mirrored else ""
    return f'{indent}val {kname}: ImageVector by lazy {{ symbolVector("{vname}", {px}, "{d}"{mirror}) }}\n'


def main():
    cache = sys.argv[1]
    os.makedirs(cache, exist_ok=True)
    os.makedirs(OUT, exist_ok=True)

    island = HEADER + """
/**
 * The island's glyphs (V7.3): weight 500, grade -25 (tuned for light-on-black), filled. The top
 * level is optical size 24 for cards; [Small] is optical size 20, drawn heavier and more open for
 * the pill, the bubble and the alert pills. Island code reaches them through `IslandIcons`.
 */
object IslandGlyphs {
"""
    for k, s in ISLAND.items():
        island += entry(k, f"Symbols.{k}", fetch(cache, s, ISLAND_STYLE, 24), 24, k in ISLAND_MIRRORED)
    island += "\n    /** Optical size 20: the pill, the bubble and the alert pills. */\n    object Small {\n"
    for k, s in ISLAND.items():
        island += entry(k, f"Symbols.{k}.20", fetch(cache, s, ISLAND_STYLE, 20), 20, k in ISLAND_MIRRORED, "        ")
    island += "    }\n}\n"
    open(os.path.join(OUT, "IslandGlyphs.kt"), "w", encoding="utf-8", newline="\n").write(island)

    app = HEADER + """
/** The settings app's icons (V7.3): Material Symbols Rounded, weight 400, filled, optical size 24. */
object AppIcons {
"""
    for k, s in APP.items():
        app += entry(k, f"Symbols.App.{k}", fetch(cache, s, APP_STYLE, 24), 24, k in APP_MIRRORED)
    app += "}\n"
    open(os.path.join(OUT, "AppIcons.kt"), "w", encoding="utf-8", newline="\n").write(app)
    print(f"{len(ISLAND) * 2} island glyphs, {len(APP)} app icons")


if __name__ == "__main__":
    main()
